LOCALES = {'en': EN, 'fr': FR, 'es': ES, 'pt': PT, 'zh': ZH, 'ar': AR}


def flat(d, p=''):
    out = {}
    for k, v in d.items():
        key = k if p == '' else p + '.' + k
        if isinstance(v, dict):
            out.update(flat(v, key))
        else:
            out[key] = v
    return out


def placeholders(s):
    return sorted(set(re.findall(r'\{\d+\}', s)))


# --- parity assertions before touching any file
en_flat = flat(EN)
for loc, d in LOCALES.items():
    lf = flat(d)
    missing = sorted(set(en_flat) - set(lf))
    stray = sorted(set(lf) - set(en_flat))
    assert not missing, f'{loc} missing: {missing}'
    assert not stray, f'{loc} stray: {stray}'
    for k, v in en_flat.items():
        assert placeholders(v) == placeholders(lf[k]), f'{loc}.{k} placeholder drift'
print('parity ok:', len(en_flat), 'keys x', len(LOCALES), 'locales')


def emit(d, indent=4):
    """Render a nested dict as a PHP array literal body."""
    pad = ' ' * indent
    lines = []
    for k, v in d.items():
        if isinstance(v, dict):
            lines.append(f"{pad}'{k}' => [")
            lines.append(emit(v, indent + 4))
            lines.append(f"{pad}],")
        else:
            esc = v.replace('\\', '\\\\').replace("'", "\\'")
            lines.append(f"{pad}'{k}' => '{esc}',")
    return '\n'.join(lines)


for loc, d in LOCALES.items():
    path = ROOT / loc / 'Events.php'
    src = path.read_text()
    assert "\n    'committee' => [" not in src, f'{loc} already patched'
    # Insert before the final "];" that closes the returned array.
    idx = src.rstrip().rfind('\n];')
    assert idx > 0, f'{loc}: closing bracket not found'
    body = src[:idx].rstrip('\n')
    block = '\n\n    // Event committees — optional pre-event project management (see\n    // docs/EVENT_COMMITTEE_REVIEW.md). Keys are grouped: `committee` governance,\n    // `plan` work engine, `decision` oversight queue.\n'
    block += emit(d) + '\n'
    path.write_text(body + block + '];\n')
    print('patched', loc)
